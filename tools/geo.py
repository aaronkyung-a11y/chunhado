LAT0 = 33.0
KM_PER_DEG = 111.2

def to_km(lat, lon):
    """등장방형 투영(기준 위도 33°) — 동쪽 x, 남쪽 y (km)."""
    return (lon * math.cos(math.radians(LAT0)) * KM_PER_DEG, -lat * KM_PER_DEG)

# ---- 람베르트 정각원추도법 (표준위선 27°·39°, 중심 33°N 112°E) ----
import numpy as np
R_E = 6371.0
PHI1, PHI2, PHI0, LAM0 = [math.radians(v) for v in (27.0, 39.0, 33.0, 112.0)]
_n = math.log(math.cos(PHI1) / math.cos(PHI2)) / math.log(math.tan(math.pi / 4 + PHI2 / 2) / math.tan(math.pi / 4 + PHI1 / 2))
_F = math.cos(PHI1) * math.tan(math.pi / 4 + PHI1 / 2) ** _n / _n
_rho0 = _F / math.tan(math.pi / 4 + PHI0 / 2) ** _n

def lcc_fwd(lat, lon):
    """(위도, 경도) → (동쪽 x km, 북쪽 y km)"""
    lat = np.radians(np.asarray(lat, dtype=np.float64)); lon = np.radians(np.asarray(lon, dtype=np.float64))
    rho = _F / np.tan(np.pi / 4 + lat / 2) ** _n
    th = _n * (lon - LAM0)
    return R_E * rho * np.sin(th), R_E * (_rho0 - rho * np.cos(th))

def lcc_inv(x, y):
    x = np.asarray(x, dtype=np.float64) / R_E; y = np.asarray(y, dtype=np.float64) / R_E
    rho = np.hypot(x, _rho0 - y)
    th = np.arctan2(x, _rho0 - y)
    lat = 2 * np.arctan((_F / rho) ** (1 / _n)) - np.pi / 2
    return np.degrees(lat), np.degrees(LAM0 + th / _n)
