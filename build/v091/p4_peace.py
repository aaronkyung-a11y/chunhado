import io
def rep(s, a, b, n=1):
    c = s.count(a)
    assert c == n, (c, a[:110])
    return s.replace(a, b)
p = 'src/data.js'; s = io.open(p, encoding='utf-8').read()
s = rep(s, "var PEACE_ALL = 12;", "var PEACE_ALL = 9;                                     // v0.8.1~0.9: 12")
s = rep(s, "var PEACE_PLAYER = [[10000, 36], [20000, 24]];      // [시작 병력이 이보다 적으면, 보호 턴 수] — 그 밖은 PEACE_ALL",
           "var PEACE_PLAYER = [[10000, 18], [20000, 12]];      // [시작 병력이 이보다 적으면, 보호 턴 수] — 그 밖은 PEACE_ALL. v0.8.1~0.9: 36 / 24 ('좀 긴 것 같다')")
io.open(p, 'w', encoding='utf-8').write(s)
