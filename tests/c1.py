# v0.3: STATUS 창 · 출진(목적지) · 턴 재생 — 화면 확인용
from browser import *
import browser
browser.SHOTS = os.path.join(ROOT, 'shots3')
def steps(pg):
    start(pg, int(os.environ.get('FAC', '2')))
    shot(pg, 'c1_home', 900)
    info = pg.evaluate('''() => { var sa = safeArea(); return { CH: CH, sa: sa, sheet: $('sheet').offsetHeight, bar: $('bar').offsetHeight, hud: $('hud').offsetHeight, todo: document.querySelectorAll('.todo').length, need: todoList().need }; }''')
    print('layout', info)
    tapsel(pg, '#sheet [data-a=fold]'); shot(pg, 'c1_home_fold', 500)
    tapsel(pg, '#sheet [data-a=fold]')
    # 할 일 첫 줄(거점) → 거점 창
    idx = pg.evaluate('''() => { var t = todoList(); for (var i = 0; i < t.length; i++) if (t[i].go && t[i].go[0] === 'base') return i; return -1; }''')
    print('first base todo', idx)
    tapsel(pg, '#sheet .todo', idx); shot(pg, 'c1_base', 900)
    tapsel(pg, '#sheet [data-a=tab][data-v=mil]'); tapsel(pg, '#sheet [data-a=deploy]')
    tapsel(pg, '#modal [data-a=auto]'); pg.wait_for_timeout(300)
    shot(pg, 'c1_deploy_a', 400)
    n = pg.evaluate('document.querySelectorAll("#modal .dest").length'); print('dest options', n, pg.evaluate('Array.from(document.querySelectorAll("#modal .dest")).map(function (e) { return e.innerText.replace(/\\n/g, " / "); })'))
    pg.evaluate('document.querySelector("#modal .dests").scrollIntoView()')
    tapsel(pg, '#modal .dest:not(.wide):not(.off)', 0)
    pg.evaluate('document.querySelector("#modal .dests").scrollIntoView()')
    shot(pg, 'c1_deploy_b', 400)
    print('ok label', pg.evaluate('document.querySelector("#modal [data-a=ok]").innerText'))
    before = pg.evaluate('G.units.length')
    tapsel(pg, '#modal [data-a=ok]'); pg.wait_for_timeout(2500)
    st = pg.evaluate('''() => { var u = facUnits(G.player)[0]; return u ? { n: uName(u), c: u.c, r: u.r, dest: u.dest, destName: u.dest >= 0 ? destName(u.dest) : null, mp: u.mp, moved: u.moved, busy: UI.busy, sel: UI.sel, toast: $('toast').textContent } : null; }''')
    print('after deploy', before, '->', pg.evaluate('G.units.length'), st)
    shot(pg, 'c1_after_deploy', 600)
    # 턴 종료 → 재생
    pg.evaluate('clearSel()'); pg.wait_for_timeout(300)
    shot(pg, 'c1_home2', 400)
    d0 = pg.evaluate('dateStr()')
    tapsel(pg, '#btnEnd'); pg.wait_for_timeout(300)
    if not pg.evaluate('!!UI.play'): tapsel(pg, '#btnEnd')
    pg.wait_for_timeout(700); print('playing', pg.evaluate('!!UI.play'), pg.evaluate('$("plMsg").innerText'))
    shot(pg, 'c1_play_1', 100)
    t0 = time.time(); seen = []
    while pg.evaluate('!!UI.play') and time.time() - t0 < 120:
        m = pg.evaluate('$("plFac").innerText + " | " + $("plMsg").innerText')
        if not seen or seen[-1] != m: seen.append(m)
        pg.wait_for_timeout(150)
    print('playback took %.1fs' % (time.time() - t0)); print('captions', seen)
    pg.wait_for_timeout(600)
    print('date', d0, '->', pg.evaluate('dateStr()'), 'modal', pg.evaluate('MODAL ? document.querySelector("#modal h2").innerText : null'), 'busy', pg.evaluate('UI.busy'), 'report', pg.evaluate('REPORT.length'))
    shot(pg, 'c1_report', 400)
    if pg.evaluate('!!MODAL'): tapsel(pg, '#modal [data-a=close]')
    u = pg.evaluate('''() => { var u = facUnits(G.player)[0]; return u ? { c: u.c, r: u.r, dest: u.dest, mp: u.mp, max: uMaxMp(u), done: u.done, moved: u.moved } : null; }''')
    print('unit at new turn', u)
    shot(pg, 'c1_turn2', 600)
run(steps, 390, 844, 2)
print('ERRORS', [e for e in errors if 'ReadPixels' not in e and 'ERR_FILE_NOT_FOUND' not in e and 'ERR_FAILED' not in e][:8])
