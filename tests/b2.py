from browser import *
def steps(pg):
    start(pg, 0)
    b = pg.evaluate('(function(){ var L = off(G.factions[G.player].lord), b = G.bases[L.loc]; return [b.c, b.r, b.id]; })()')
    taphex(pg, b[0], b[1]); shot(pg, '10_city')
    tapsel(pg, '#sheet [data-a=draft]'); shot(pg, '11_pick')
    tapsel(pg, '#modal [data-a=auto]'); shot(pg, '12_pick_auto')
    tapsel(pg, '#modal [data-a=auto]'); shot(pg, '12b_pick_auto1')
    tapsel(pg, '#modal [data-a=auto]'); tapsel(pg, '#modal [data-a=ok]'); shot(pg, '13_after_draft')
    tapsel(pg, '#sheet [data-a=tab][data-v=fac]'); shot(pg, '14_fac_tab')
    pg.locator('#sheet [data-a=plot]').filter(has_text='빈 부지').first.tap(); pg.wait_for_timeout(300); shot(pg, '15_develop')
    tapsel(pg, '#modal [data-a=f][data-v=farm]'); tapsel(pg, '#modal [data-a=auto]'); shot(pg, '16_dev_pick'); tapsel(pg, '#modal [data-a=ok]')
    tapsel(pg, '#sheet [data-a=tab][data-v=mil]'); tapsel(pg, '#sheet [data-a=deploy]'); shot(pg, '17_deploy')
    tapsel(pg, '#modal [data-a=auto]'); shot(pg, '18_deploy_auto')
    pg.locator('#modal .dlg-b').evaluate('e => e.scrollTop = e.scrollHeight'); shot(pg, '19_deploy_food')
    tapsel(pg, '#modal [data-a=ok]'); shot(pg, '20_unit', 800)
    # 먼 거점(허창)을 눌러 행군
    hc = pg.evaluate('(function(){ var b = G.bases[baseByName("허창")]; return [b.c, b.r]; })()')
    pg.evaluate('([c,r]) => onTap(c, r)', hc); shot(pg, '21_march_prop')
    tapsel(pg, '#sheet [data-a=march]'); shot(pg, '22_marching', 1500)
    print('unit', pg.evaluate('JSON.stringify(G.units.filter(function(u){return u.f===G.player}).map(function(u){return [u.c,u.r,u.dest,u.mp,u.done]}))'))
    pg.evaluate('clearSel()'); pg.wait_for_timeout(200)
    tapsel(pg, '#btnEnd'); pg.wait_for_timeout(300)
    if pg.locator('#modal.on').count() == 0: tapsel(pg, '#btnEnd')
    pg.wait_for_timeout(1500); shot(pg, '23_report')
    print('unit', pg.evaluate('JSON.stringify(G.units.filter(function(u){return u.f===G.player}).map(function(u){return [u.c,u.r,u.dest,u.mp,u.done]}))'), pg.evaluate('dateStr()'))
run(steps)
print('ERRORS', [e for e in errors if 'ReadPixels' not in e and 'ERR_FILE_NOT_FOUND' not in e][:12])
